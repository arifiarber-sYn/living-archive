"""gjenero_pyetje_peps.py — a larger PEP question set with ground truth BY CONSTRUCTION.

  python3 harness/gjenero_pyetje_peps.py [--n 80] [--kurthe 20] [--seed 13]

For each sampled PEP, Nemotron (Token Factory) writes ONE question answerable from that PEP's lead text, without naming
the PEP number or title. The expected id is the PEP the question was generated from — so the label needs no human
labelling, but a question may also be answerable by a sibling PEP (we keep that noise and say so in the README).
Traps: PEP numbers that do not exist in the corpus + off-domain questions (must be refused).
Writes harness/pyetjet-peps-100.json. Cost ≈ $0.03 (one short call per PEP). Deterministic sample (seed).
"""
from __future__ import annotations

import argparse
import json
import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent))
from src.know import _thirr, _teksti  # noqa: E402

RRENJA = pathlib.Path(__file__).resolve().parent.parent
PEPS = RRENJA / 'arkiva-peps'
JASHTE_DOMENIT = [
    'What is the classic recipe for Albanian byrek with spinach?',
    'Who won the 2018 FIFA World Cup?',
    'How do I configure a Rust borrow checker in Python?',
    'What is the boiling point of mercury at sea level?',
    'Which PEP sets the release date of Python 5.0?',
    'What does the Java Community Process say about generics?',
    'How many moons does Jupiter have?',
    'Which PEP mandates tabs over spaces for the C implementation of Go?',
]


def koka(teksti: str) -> tuple[str, str]:
    """(title, lead text without front-matter and without the '# PEP N — Title' line)."""
    pjese = teksti.split('---', 2)
    fm, trupi = pjese[1], pjese[2] if len(pjese) == 3 else ('', teksti)
    titulli = next((r.split(':', 1)[1].strip() for r in fm.splitlines() if r.startswith('titulli:')), '')
    rreshta = [r for r in trupi.strip().splitlines() if not r.startswith('# PEP ')]
    return titulli, '\n'.join(rreshta)[:1500]


def pyetje_per(ident: str, titulli: str, lead: str) -> str:
    sistemi = ('You write ONE evaluation question for a retrieval system. The question must be answerable from the text '
               'below, must NOT mention the PEP number or its title words verbatim, must be specific enough that this text '
               'is the best answer, and must be a single English sentence ending with a question mark. Output only the question.')
    d = _thirr([{'role': 'system', 'content': sistemi},
                {'role': 'user', 'content': 'PEP id: ' + ident + '\nTitle (do not repeat): ' + titulli + '\n\nText:\n' + lead}],
               max_tokens=80, temp=0.3)
    q = _teksti(d).strip().strip('"').splitlines()[0].strip()
    return q if q.endswith('?') else q + '?'


def main() -> int:
    a = argparse.ArgumentParser()
    a.add_argument('--n', type=int, default=80)
    a.add_argument('--kurthe', type=int, default=20)
    a.add_argument('--seed', type=int, default=13)
    a.add_argument('--out', default='pyetjet-peps-100.json')
    ns = a.parse_args()
    rnd = random.Random(ns.seed)
    skedaret = sorted(PEPS.glob('pep-*.md'))
    ekzistojne = {p.stem for p in skedaret}
    # prefer substantive PEPs: skip very short units (meta/withdrawn stubs)
    kandidate = [p for p in skedaret if p.stat().st_size > 2500]
    zgjedhur = rnd.sample(kandidate, ns.n)
    pyetjet = []
    for i, p in enumerate(zgjedhur, 1):
        titulli, lead = koka(p.read_text(encoding='utf-8', errors='replace'))
        q = pyetje_per(p.stem, titulli, lead)
        pyetjet.append({'id': 'g%03d' % i, 'pyetja': q, 'pret': [p.stem], 'titulli': titulli})
        print(p.stem, '|', q[:110], flush=True)
    # traps: non-existent PEP numbers (not in corpus) + off-domain
    numra = [n for n in range(1000, 9999) if ('pep-%04d' % n) not in ekzistojne]
    rnd.shuffle(numra)
    kurthe_pep = ns.kurthe - min(len(JASHTE_DOMENIT), ns.kurthe // 2)
    for j, n in enumerate(numra[:kurthe_pep], 1):
        pyetjet.append({'id': 'k%03d' % j, 'pyetja': 'What does PEP %d propose?' % n, 'refuzim': True})
    for j, q in enumerate(JASHTE_DOMENIT[:ns.kurthe - kurthe_pep], 1):
        pyetjet.append({'id': 'x%03d' % j, 'pyetja': q, 'refuzim': True})
    out = {'shkalla': '2026-10-13 (generated, seed %d)' % ns.seed,
           'pershkrimi': 'Ground truth by construction: each answerable question was generated by Nemotron from the lead text of '
                         'the expected PEP (number/title withheld). Traps = PEP numbers absent from the corpus + off-domain. '
                         'A question may be answerable by a sibling PEP; that noise is kept, not hand-fixed.',
           'pyetjet': pyetjet}
    (RRENJA / 'harness' / ns.out).write_text(json.dumps(out, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print('shkruar:', ns.out, len(pyetjet), 'pyetje')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
